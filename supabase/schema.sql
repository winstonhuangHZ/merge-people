-- 合成人物完整历史排行榜
-- 在 Supabase SQL Editor 中执行一次；可重复执行。

create table if not exists public.leaderboard_scores (
  id bigint generated by default as identity primary key,
  player_id uuid not null,
  nickname text not null,
  score integer not null,
  created_at timestamptz not null default now(),
  constraint leaderboard_nickname_valid check (
    nickname = btrim(nickname)
    and char_length(nickname) between 1 and 12
  ),
  constraint leaderboard_score_valid check (
    score between 1 and 99999999
  )
);

create index if not exists leaderboard_scores_rank_idx
  on public.leaderboard_scores (score desc, created_at desc);

alter table public.leaderboard_scores enable row level security;

grant usage, select on sequence public.leaderboard_scores_id_seq to anon, authenticated;
grant select on table public.leaderboard_scores to anon, authenticated;
grant insert (player_id, nickname, score) on table public.leaderboard_scores to anon, authenticated;

drop policy if exists "leaderboard public read" on public.leaderboard_scores;
create policy "leaderboard public read"
  on public.leaderboard_scores for select
  to anon, authenticated
  using (true);

drop policy if exists "leaderboard public insert" on public.leaderboard_scores;
create policy "leaderboard public insert"
  on public.leaderboard_scores for insert
  to anon, authenticated
  with check (
    nickname = btrim(nickname)
    and char_length(nickname) between 1 and 12
    and score between 1 and 99999999
  );
